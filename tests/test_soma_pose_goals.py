def library(rep, raw):
    poses = raw[0, [0, 20]].clone()
    return {"schema": "motionbricks.train_pose_library.v1", "features": poses,
            "local_velocity_xz_mps": torch.tensor([[0., 0.], [0., 1.]]),
            "provenance": [{"split": "train", "frame": i} for i in (0, 20)]}


def test_training_conditions_one_endpoint_and_no_hidden_middle():
    rep, root, pose = models()
    raw = source_motion(rep)
    local = rep.dual_rep.global_to_local(raw, True, True, lengths=torch.tensor([65]))[:, :64]
    for model in (root, pose):
        model.args["body_goal_policy"] = "single_endpoint"
    values, mask, _, _ = pose._sample_the_local_pose_conditions(local, 64)
    assert mask[0].nonzero().flatten().tolist() == [0, 1, 2, 3, 63]
    assert not values[:, 4:-1].any()
    sparse, sparse_mask = root._sample_the_conditions(values, 64)
    assert sparse_mask[0].nonzero().flatten().tolist() == [0, 1, 2, 3, 7]
    torch.testing.assert_close(sparse[:, -1], values[:, -1])


def test_external_goal_not_source_future_even_for_goal_trained_model():
    rep, _, pose = models()
    pose.args["body_goal_policy"] = "single_endpoint"
    pose.eval()
    raw = source_motion(rep)
    local = rep.dual_rep.global_to_local(raw, True, True, lengths=torch.tensor([65]))[:, :64]
    changed = local.clone()
    changed[:, 4:, 4:] += 100
    goal = local[:, -4:].clone()
    with torch.no_grad():
        expected = pose.predict_local(local, raw[:, :64], goal_local=goal)
        actual = pose.predict_local(changed, raw[:, :64], goal_local=goal)
        unconditioned = pose.predict_local(local, raw[:, :64])
    torch.testing.assert_close(expected[0]["pose_logits"], actual[0]["pose_logits"])
    torch.testing.assert_close(expected[1], actual[1])
    assert not torch.allclose(expected[0]["pose_logits"], unconditioned[0]["pose_logits"])


def test_reference_library_uses_native_heading_and_never_mutates_source():
    rep, _, _ = models()
    raw = rep.unnormalize(source_motion(rep))
    payload = library(rep, raw)
    reference = ReferencePoseLibrary(payload, rep, "cpu")
    original = payload["features"].clone()
    endpoint = raw[:, -4:, :5].repeat(2, 1, 1)
    endpoint[..., 0] += 5
    heading = torch.tensor([0., torch.pi / 2])
    # Command world directions are generated by the same official yaw convention.
    probe = raw[:, :2].repeat(2, 1, 1).clone()
    probe[:, :, :3] = 0
    probe[:, 1, 2] = 1
    rotated = rep.change_first_heading(probe, heading, False, False)
    target, mask, ids = reference.select(rotated[:, 1, [0, 2]], heading, endpoint)
    assert ids.tolist() == [1, 1]
    assert mask.sum(1).tolist() == [1, 1]
    torch.testing.assert_close(target[..., [0, 2]], endpoint[..., [0, 2]])
    expected = rep.change_first_heading(original[ids, None], heading, False, False)
    torch.testing.assert_close(target[:, :1, 5:], expected[..., 5:])
    torch.testing.assert_close(payload["features"], original)


@pytest.mark.parametrize("split", ["validation", "test"])
def test_reference_library_rejects_non_training_provenance(split):
    rep, _, _ = models()
    raw = rep.unnormalize(source_motion(rep))
    payload = library(rep, raw)
    payload["provenance"][0]["split"] = split
    with pytest.raises(ValueError, match="non-training"):
        ReferencePoseLibrary(payload, rep, "cpu")
    selected = library_records([{"split": "train", "frames_60hz": 129},
                                {"split": split, "frames_60hz": 300}])
    assert len(selected) == 1 and selected[0]["split"] == "train"


@pytest.mark.parametrize("batch_size", [1, 2])
def test_control_goals_reach_root_pose_and_official_decoder(monkeypatch, batch_size):
    rep, root, pose = models()
    inference = SomaMotionInference({"root": root, "pose": pose},
        {"min_tokens": 6, "max_tokens": 16, "cond_root_feature_is_from_motion_rep": "global"}, device="cpu")
    raw = rep.unnormalize(source_motion(rep))
    ref = ReferencePoseLibrary(library(rep, raw), rep, "cpu")
    raw = raw.repeat(batch_size, 1, 1)
    target, mask, _ = ref.select([[0., 1.]] * batch_size, [0.] * batch_size, raw[:, -4:, :5])
    target[..., 1] = 1.15
    inputs = control_inputs(raw[:, :4], raw[:, -4:, :5], torch.tensor([[0., 1.]] * batch_size), rep, target, mask)
    assert inputs[-1][0].nonzero().flatten().tolist() == [0, 1, 2, 3, 7]
    assert inputs[0][0, -1, 1] == pytest.approx(1.15)
    assert inputs[2][0, -1, 3] == pytest.approx(1.15)
    seen = {}
    def root_hook(module, args):
        seen["root"] = args[5].clone()
    def pose_hook(module, args):
        seen["pose"] = args[3].clone()
    handles = [root.backbone_net.register_forward_pre_hook(root_hook),
               pose.backbone_net.register_forward_pre_hook(pose_hook)]
    original = pose.pose_net.forward_decoder
    def decoder(*args, **kwargs):
        seen["decoder"] = args[2].clone()
        return original(*args, **kwargs)
    monkeypatch.setattr(pose.pose_net, "forward_decoder", decoder)
    with torch.inference_mode():
        result, _ = inference.predict(*inputs, 16, config={"pose_token_sampling_use_argmax": True})
    for handle in handles:
        handle.remove()
    assert torch.isfinite(result).all()
    assert seen["root"][0].nonzero().flatten().tolist() == [0, 1, 2, 3, 7]
    for key in ("pose", "decoder"):
        assert seen[key][0].nonzero().flatten().tolist() == [0, 1, 2, 3, 63]


def test_native_training_objectives_update_root_pose_and_freeze_tokenizer():
    from scripts.train_soma_pose_goals import native_losses
    rep, root, pose = models()
    for model in (root, pose):
        model.args["body_goal_policy"] = "single_endpoint"
    raw = source_motion(rep)
    local = rep.dual_rep.global_to_local(raw, True, True, lengths=torch.tensor([65]))[:, :64]
    before = state_digest(pose.pose_net)
    root_loss, pose_loss, terms = native_losses(root, pose, raw[:, :64], local)
    (root_loss + pose_loss).backward()
    assert terms["body_goal_frames"].item() == 1
    for model in (root, pose):
        assert any(p.grad is not None and torch.isfinite(p.grad).all() and p.grad.abs().sum() > 0
                   for p in model.backbone_net.parameters())
    assert all(p.grad is None for p in pose.pose_net.parameters())
    assert state_digest(pose.pose_net) == before


def test_external_goal_requires_mask_and_rejects_dense_four_frame_targets():
    rep, _, _ = models()
    history = rep.unnormalize(source_motion(rep))[:, :4]
    with pytest.raises(ValueError, match="both"):
        control_inputs(history, history[..., :5], torch.zeros(1, 2), rep, history)
    with pytest.raises(ValueError, match="one finite"):
        control_inputs(history, history[..., :5], torch.zeros(1, 2), rep,
                       history, torch.ones(1, 4, dtype=torch.bool))


@pytest.mark.parametrize("skin_device", ["cpu", "cuda"])
def test_evaluation_skin_contact_path_uses_all_source_joints_and_shared_masks(skin_device):
    from scripts.evaluate_soma_pose_goals import compare_contact
    from motionbricks.data.bones_seed import official_sole_surfaces
    from motionbricks.data.soma_skin_reference import load_official_skinner, move_skinner
    from motionbricks.data.sole_region_contact import sole_region_indices
    rep, _, _ = models()
    raw = rep.unnormalize(source_motion(rep))[:, :64]
    surfaces, _, _, _ = official_sole_surfaces(rep.skeleton)
    indices = {side: sole_region_indices(surfaces, side) for side in ("Left", "Right")}
    if skin_device == "cuda" and not torch.cuda.is_available():
        pytest.skip("CUDA is not available")
    skinner = move_skinner(load_official_skinner(rep.skeleton), skin_device)
    result = compare_contact(raw, raw, rep, skinner, indices)
    assert result["source_contact"] == result["predicted_contact"]


def test_automatic_gate_rejects_quality_regression_without_promoting_passing_checks(tmp_path):
    from scripts.summarize_soma_pose_goals import summarize
    names = ("review_original", "review_A_v3", "review_B_library", "review_B_no_goals")
    for index, name in enumerate(names):
        path = tmp_path / name
        path.mkdir()
        report = {"evaluation_sha256": "same", "test_used": False, "post_processing": None,
            "windows": [{"filename": "validation", "start": 0, "input_sha256": "same",
                         "source_contact": {}, "predicted_contact": {"valid_samples": {"n": 1}}}],
            "aggregate": {"windows": 1, "worst_joint_step_deg": 2 if index == 2 else 1},
            "rollouts": {str(delay): {"boundary_joint_step_mm": {"p95": 1},
                "angular_step_deg": {"max": 1}, "root_command_velocity_error_mps": {"mean": 1}}
                         for delay in (0, 12)}}
        (path / "metrics.json").write_text(json.dumps(report))
    for name in ("A", "B"):
        path = tmp_path / "contracts" / name
        path.mkdir(parents=True)
        (path / "result.json").write_text(json.dumps({"sampling_sha256": "same", "steps_per_stage": 10,
                                                     "tokenizer_unchanged": True}))
        (path / "contract.json").write_text(json.dumps({key: "same" for key in (
            "initial_bundle_sha256", "dataset_sha256", "seed", "train_clips", "lr", "batch", "objectives")}))
    report = summarize(tmp_path)
    assert report["matched_scoring_verified"]
    assert report["deployment_decision"] == "rejected_regression"
    assert report["quality_approved"] is False
    altered = json.loads((tmp_path / names[-1] / "metrics.json").read_text())
    altered["windows"][0]["predicted_contact"]["valid_samples"]["n"] = 2
    (tmp_path / names[-1] / "metrics.json").write_text(json.dumps(altered))
    with pytest.raises(ValueError, match="identity"):
        summarize(tmp_path)
